"""inventory.py — experiment inventory for the PLOS ONE revision (PONE-D-26-31648).

Scans the canonical results tree and reports, computed from the files themselves:
cells (experiment x dataset x method x condition), row counts against each cell's own
expected size, empty/NaN rows, duplicate keys, and which summary tables exist.

CPU-only, seconds. Run:
    .venv/bin/python revision/scripts/inventory.py                 # default roots
    .venv/bin/python revision/scripts/inventory.py inv.results_roots='[github_repo/results,revision/experiments]'
    .venv/bin/python revision/scripts/inventory.py --write-config  # dump conf/inventory.yaml
"""
from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path

import hydra
import pandas as pd
from hydra.core.config_store import ConfigStore
from omegaconf import OmegaConf

PROJECT = Path(__file__).resolve().parents[2]

COND_COLS = ["tier", "p", "k", "K", "threshold_pct", "part", "n_vs_psi", "d"]
METRIC_COLS = ["rho", "rho_tilde", "rho_srs", "rho_str", "rho_cluster"]


@dataclass
class InvConfig:
    results_roots: list = field(default_factory=lambda: ["github_repo/results", "revision/experiments"])
    tables_roots: list = field(default_factory=lambda: ["github_repo/tables", "revision/experiments/tables"])
    out_md: str = "revision/inventory.md"
    rep_col: str = "rep"


@dataclass
class RootConfig:
    inv: InvConfig = field(default_factory=InvConfig)


ConfigStore.instance().store(name="inventory", node=RootConfig)


def summarize(path: Path, rep_col: str) -> list[str]:
    df = pd.read_csv(path, low_memory=False)
    out = [f"### `{path.relative_to(PROJECT)}` — {len(df):,} rows, {df.shape[1]} cols", ""]
    cond = [c for c in COND_COLS if c in df.columns]
    keys = [c for c in ["dataset", "method"] if c in df.columns] + cond
    for c in ["method", "dataset", "tier", "p", "method_class"]:
        if c in df.columns:
            vals = sorted(df[c].dropna().astype(str).unique())
            out.append(f"- **{c}** ({len(vals)}): {', '.join(vals)}")
    metrics = [c for c in METRIC_COLS if c in df.columns]
    for m in metrics:
        out.append(f"- NaN in `{m}`: {int(df[m].isna().sum()):,}")
    if "error" in df.columns:
        out.append(f"- rows with non-empty `error`: {int(df['error'].notna().sum()):,}")
    if rep_col in df.columns and keys:
        dup = int(df.duplicated(keys + [rep_col]).sum())
        out.append(f"- duplicate (keys+{rep_col}) rows: {dup:,}")
        cells = df.groupby(keys, dropna=False)[rep_col].nunique()
        group = [c for c in ["tier"] if c in keys]
        if group:
            expected = cells.groupby(level=group).transform("max")
        else:
            expected = pd.Series(cells.max(), index=cells.index)
        short = cells[cells < expected]
        out.append(f"- cells: {len(cells):,}; reps/cell min={cells.min()} max={cells.max()}; "
                   f"cells below their group's max: {len(short):,}")
        if len(short):
            out.append("  - short cells (first 15): " + "; ".join(
                f"{k}={v}" for k, v in list(short.items())[:15]))
    if "method" in df.columns and "dataset" in df.columns:
        grid = df.groupby(["method", "dataset"]).size().unstack(fill_value=0)
        missing = [(m, d) for m in grid.index for d in grid.columns if grid.loc[m, d] == 0]
        out.append(f"- method×dataset grid {grid.shape[0]}×{grid.shape[1]}; empty cells: {len(missing)}")
        if missing:
            out.append("  - empty: " + ", ".join(f"{m}/{d}" for m, d in missing[:40])
                       + (" …" if len(missing) > 40 else ""))
    out.append("")
    return out


@hydra.main(version_base=None, config_name="inventory")
def main(cfg: RootConfig) -> None:
    lines = ["# Experiment inventory (computed from files — regenerate, do not edit)", "",
             "Generated by `revision/scripts/inventory.py`.", ""]
    for root in cfg.inv.results_roots:
        r = PROJECT / root
        lines.append(f"## Results root `{root}`" + ("" if r.exists() else " — (absent)"))
        lines.append("")
        for f in sorted(r.rglob("*.csv")) if r.exists() else []:
            try:
                lines += summarize(f, cfg.inv.rep_col)
            except Exception as e:
                lines += [f"### `{f}` — FAILED TO PARSE: {e}", ""]
    for root in cfg.inv.tables_roots:
        r = PROJECT / root
        lines.append(f"## Tables root `{root}`" + ("" if r.exists() else " — (absent)"))
        for f in sorted(r.glob("*.csv")) if r.exists() else []:
            n = len(pd.read_csv(f))
            lines.append(f"- `{f.name}` ({n} rows)")
        lines.append("")
    out = PROJECT / cfg.inv.out_md
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    if "--write-config" in sys.argv:
        (PROJECT / "conf").mkdir(exist_ok=True)
        (PROJECT / "conf" / "inventory.yaml").write_text(OmegaConf.to_yaml(OmegaConf.structured(RootConfig)))
        print("wrote conf/inventory.yaml")
        sys.exit(0)
    sys.argv.append("hydra.run.dir=.")
    sys.argv.append("hydra.output_subdir=null")
    main()
